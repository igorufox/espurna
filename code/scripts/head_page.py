# The head's own page (espurna/modules_page.html, modules.cpp: `/` while there is no webui module, /modules.html), every
# chip: gzip'ed into $BUILD_DIR/generated/modules_page_gz.h before the build, served gzip'ed (the HTTP header says so) as the
# WebUI parts are. The page in the image was the plain HTML, 12 KB of the head; gzip'ed it is under 5 KB.
#
# pre: extra script of platformio_esp8266.ini, platformio_esp32.ini and platformio_beken.ini

import gzip
import os

Import("env")  # noqa: F821
env = globals()["env"]

SOURCE = os.path.join(env.subst("$PROJECT_DIR"), "espurna", "modules_page.html")
OUT_DIR = os.path.join(env.subst("$BUILD_DIR"), "generated")
OUT = os.path.join(OUT_DIR, "modules_page_gz.h")


def header(data):
    lines = []
    for start in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{byte:02x}" for byte in data[start: start + 24]) + ",")
    return "\n".join([
        "// generated by scripts/head_page.py from espurna/modules_page.html: do not edit",
        "#pragma once",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "",
        "namespace espurna {",
        "namespace modules {",
        "",
        "alignas(4) static constexpr uint8_t HeadPageGz[] = {",
        *lines,
        "};",
        "",
        "} // namespace modules",
        "} // namespace espurna",
        "",
    ])


def generate():
    with open(SOURCE, "rb") as f:
        # mtime 0: the same page gives the same bytes, the build does not change without a change of the page
        data = gzip.compress(f.read(), 9, mtime=0)
    text = header(data)
    os.makedirs(OUT_DIR, exist_ok=True)
    old = None
    if os.path.isfile(OUT):
        with open(OUT, "r", encoding="utf-8") as f:
            old = f.read()
    if old != text:
        with open(OUT, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"head_page.py: modules_page.html, {len(data)} bytes gzip'ed")


generate()
env.Append(CPPPATH=[OUT_DIR])
