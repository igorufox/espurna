#!/usr/bin/env python3
# The ESP32 partition table, one reader for every place that needs it:
# - the csv of the build (esp32_4mb_safeboot.csv): esp32_merge.py takes the offsets of app0 and of the safeboot from
#   it, and writes the C header of its entries for the firmware (the table the WebUI migration writes,
#   arch/esp32/safeboot_esp32.cpp: ESPURNA_PARTITION_ENTRIES of esp32_partition_csv.h)
# - the binary table at 0x8000 of a merged image: the Pages job of .github/workflows/esp32.yml cuts the safeboot
#   (factory) and ESPurna (ota_0) out of the release's merged .bin
#   python3 code/scripts/esp32_partitions.py split site/*/espurna-esp32*.bin
# The firmware side of the binary table (32-byte entries) is espurna/libs/esp32_partitions.h.
#
# No SCons here: esp32_merge.py imports it, the CI runs it as a plain script.

import argparse
import collections
import os
import struct
import sys

TABLE_OFFSET = 0x8000
TABLE_SIZE = 0xC00
ENTRY = struct.Struct("<2sBBII16sI")  # magic 0xAA 0x50, type, subtype, offset, size, label, flags
MAGIC = b"\xaa\x50"

TYPES = {"app": 0x00, "data": 0x01}
SUBTYPES = {
    "app": {"factory": 0x00, "test": 0x20, **{f"ota_{index}": 0x10 + index for index in range(16)}},
    "data": {"ota": 0x00, "phy": 0x01, "nvs": 0x02, "coredump": 0x03, "nvs_keys": 0x04, "efuse": 0x05,
             "undefined": 0x06, "esphttpd": 0x80, "fat": 0x81, "spiffs": 0x82, "littlefs": 0x83},
}
APP_ALIGN = 0x10000
DATA_ALIGN = 0x1000

Entry = collections.namedtuple("Entry", "label type subtype offset size")


def number(text):
    """0x9000, 36864, 20K, 2M"""
    text = text.strip()
    scale = 1
    if text[-1:].upper() in ("K", "M"):
        scale = 1024 if text[-1:].upper() == "K" else 1024 * 1024
        text = text[:-1]
    return int(text, 0) * scale


def read_csv(path):
    """[Entry] of a partition csv; an empty offset follows the entry before it (aligned as gen_esp32part.py does)"""
    out = []
    end = TABLE_OFFSET + 0x1000
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            cols = [col.strip() for col in line.split(",")]
            if len(cols) < 5:
                raise ValueError(f"{path}: not a partition line: {line}")
            label, kind, subtype, offset, size = cols[:5]
            ptype = TYPES[kind] if kind in TYPES else number(kind)
            psub = SUBTYPES.get(kind, {}).get(subtype)
            if psub is None:
                psub = number(subtype)
            if offset:
                at = number(offset)
            else:
                align = APP_ALIGN if ptype == TYPES["app"] else DATA_ALIGN
                at = (end + align - 1) // align * align
            length = number(size)
            out.append(Entry(label, ptype, psub, at, length))
            end = at + length
    return out


def find(entries, ptype, subtype):
    return next((entry for entry in entries if (entry.type == ptype) and (entry.subtype == subtype)), None)


def app_offsets(entries):
    """(offset of the app slot: ota_0, else the first app; offset of the factory app when there is an ota_0 too)"""
    ota0 = find(entries, TYPES["app"], SUBTYPES["app"]["ota_0"])
    if ota0:
        factory = find(entries, TYPES["app"], SUBTYPES["app"]["factory"])
        return ota0.offset, (factory.offset if factory else None)
    apps = [entry for entry in entries if entry.type == TYPES["app"]]
    if apps:
        return apps[0].offset, None
    raise ValueError("no app partition")


def header(entries, source):
    """the C header of the entries: ESPURNA_PARTITION_ENTRIES ({type, subtype, offset, size, label}, ...) and
    ESPURNA_PARTITION_<LABEL>_OFFSET / _SIZE"""
    lines = [
        f"// generated by scripts/esp32_partitions.py from {os.path.basename(source)}, do not edit",
        "#pragma once",
        "",
        f"#define ESPURNA_PARTITIONS_CSV \"{os.path.basename(source)}\"",
        "",
        "#define ESPURNA_PARTITION_ENTRIES \\",
    ]
    for entry in entries:
        lines.append(f"    {{0x{entry.type:02X}, 0x{entry.subtype:02X}, 0x{entry.offset:X}, 0x{entry.size:X}, "
                     f"\"{entry.label}\"}}, \\")
    lines.append("")
    for entry in entries:
        name = "".join(c if c.isalnum() else "_" for c in entry.label).upper()
        lines.append(f"#define ESPURNA_PARTITION_{name}_OFFSET 0x{entry.offset:X}")
        lines.append(f"#define ESPURNA_PARTITION_{name}_SIZE 0x{entry.size:X}")
    return "\n".join(lines) + "\n"


def write_header(entries, source, target):
    """the header, written only when it changed (no rebuild of everything that includes it)"""
    text = header(entries, source)
    if os.path.exists(target):
        with open(target, encoding="utf-8") as f:
            if f.read() == text:
                return target
    os.makedirs(os.path.dirname(target), exist_ok=True)
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return target


def read_table(data, at=TABLE_OFFSET):
    """[Entry] of the binary table at `at` (a merged image: 0x8000); ends at the first entry without the magic"""
    out = []
    for pos in range(at, at + TABLE_SIZE, ENTRY.size):
        if data[pos:pos + 2] != MAGIC:
            break
        _, ptype, subtype, offset, size, label, _ = ENTRY.unpack_from(data, pos)
        out.append(Entry(label.split(b"\0", 1)[0].decode(errors="replace"), ptype, subtype, offset, size))
    return out


def image_length(data, start):
    """ESP image length: header, segments, checksum on a 16-byte boundary, SHA-256 when appended"""
    pos = 24
    for _ in range(data[start + 1]):
        _, length = struct.unpack_from("<II", data, start + pos)
        pos += 8 + length
    pos += 15 - (pos % 16)
    pos += 1
    if data[start + 23] == 1:
        pos += 32
    return pos


def split(path):
    """<name>-safeboot.bin (the factory app) and <name>-app.bin (ota_0 to the end of the file) of a merged image"""
    with open(path, "rb") as f:
        data = f.read()
    if data[:1] != b"\xff":
        return []
    entries = read_table(data)
    out = []
    factory = find(entries, TYPES["app"], SUBTYPES["app"]["factory"])
    if factory and data[factory.offset:factory.offset + 1] == b"\xe9":
        target = path[:-len(".bin")] + "-safeboot.bin"
        with open(target, "wb") as f:
            f.write(data[factory.offset:factory.offset + image_length(data, factory.offset)])
        out.append(target)
    # ESPurna alone: for Tasmota's safeboot, which takes application images only (nspanel/reference.md)
    ota0 = find(entries, TYPES["app"], SUBTYPES["app"]["ota_0"])
    if ota0 and data[ota0.offset:ota0.offset + 1] == b"\xe9":
        target = path[:-len(".bin")] + "-app.bin"
        with open(target, "wb") as f:
            f.write(data[ota0.offset:])
        out.append(target)
    return out


# the files of a release that are not merged images
SKIP = ("-ota.bin", "-full.bin", "-safeboot.bin", "-app.bin", "-modules.bin")


def main(argv=None):
    parser = argparse.ArgumentParser(description="ESP32 partition table: csv, binary table, merged images")
    sub = parser.add_subparsers(dest="command", required=True)
    cut = sub.add_parser("split", help="cut -safeboot.bin and -app.bin out of merged images")
    cut.add_argument("images", nargs="*")
    show = sub.add_parser("header", help="print the C header of a partition csv")
    show.add_argument("csv")
    args = parser.parse_args(argv)

    if args.command == "header":
        sys.stdout.write(header(read_csv(args.csv), args.csv))
        return 0

    for path in args.images:
        if not os.path.isfile(path) or os.path.basename(path).endswith(SKIP):
            continue
        for target in split(path):
            print(target, os.path.getsize(target))
    return 0


if __name__ == "__main__":
    sys.exit(main())
